for ip in $IPS; do
  echo "============================================================"
  echo "=== NMAP $ip ==="
  echo "============================================================"
  proxychains4 -q nmap -sT -Pn -T3 --max-retries 2 --host-timeout 240s \
    -p $PORTS --open -sV --version-intensity 5 $ip 2>&1
  echo
  sleep 3
done
